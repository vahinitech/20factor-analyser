"""Write docs/11-practice-map.md: every factor with its exercises and tips.

The mapping itself lives in backend/report/practice_catalog.py (FACTORS), which the
server and the report read. That file is code and names factors by number,
so this script writes the same mapping as one readable page, by factor
name, for review by teachers and the owner. CI runs it with --check, so the
page can never drift from what reports print.

    python scripts/practice_map.py          write docs/11-practice-map.md
    python scripts/practice_map.py --check  fail if it is out of date
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
from report import (
    practice_catalog as pc,
)  # noqa: E402  pylint: disable=wrong-import-position

OUT = ROOT / "docs" / "11-practice-map.md"
STAGE = {
    "focus": "Learning",
    "dev": "Improving",
    "good": "Mastering",
    "strong": "Strong",
}


def factor_names():
    """Names and ids from the committed catalogue version that serves this
    practice catalogue as it is now, translations included."""
    want = json.dumps(
        pc.browser_catalog()["factors"], sort_keys=True, ensure_ascii=False
    )
    for path in sorted((ROOT / "backend" / "catalogs").glob("*.json")):
        cat = json.loads(path.read_text())
        if "practice" not in cat:
            continue
        keys = ("why", "win", "page", "i18n", "exercises", "tips")
        served = {
            str(f["n"]): {k: f[k] for k in keys if k in f}
            for f in cat["factors"]
        }
        if json.dumps(served, sort_keys=True, ensure_ascii=False) != want:
            continue
        return {
            f["n"]: (f["name"], f["id"]) for f in cat["factors"]
        }, path.name
    sys.exit(
        "practice_map: no committed catalogue version serves this practice catalogue; run python backend/report/compact_reports.py first"
    )


def cell(text):
    return str(text or "").replace("|", "\\|").replace("\n", " ")


# The Telugu under each English line is draft wording, written with the
# catalogue and waiting for a native speaker's check.
TE_MARK = "తెలుగు (draft)"


def telugu_exercise(e):
    te = e["i18n"]["te"]
    return (
        f"| | {TE_MARK} **{cell(te['title'])}** | | {cell(te['steps'])} | "
        f"{cell(te.get('example')) or '-'} | {cell(te['check'])} | | | | |"
    )


def telugu_tip(t):
    return f"| {TE_MARK} | {cell(t['i18n']['te']['text'])} | |"


def helps(entry, names):
    """Which skills an entry helps, by name and weight (its own first)."""
    items = sorted(
        (entry.get("helps") or {}).items(), key=lambda kv: (-kv[1], int(kv[0]))
    )
    return ", ".join(f"{names[int(k)][0]} {w:g}" for k, w in items) or "-"


def render():
    names, version = factor_names()
    out = [
        "# Practice map: exercises and tips for every factor",
        "",
        "Generated by `scripts/practice_map.py` from `backend/report/practice_catalog.py`",
        f"(served as catalogue version `{version.removesuffix('.json')}`). Do not edit by hand:",
        "change the catalogue, then run the script. Design and rules:",
        "[10-practice-framework.md](10-practice-framework.md).",
        "",
        'Under each English line, marked "తెలుగు (draft)", is its Telugu: draft wording,',
        "not yet checked by a native speaker, which a native speaker must check before",
        "Telugu reaches production. Latin practice letters and words stay as written.",
        "",
        'Each exercise and tip says which skills it helps ("Helps": its own skill at 1,',
        "others 0.3 to 0.8). A report scores every candidate by how much it helps the",
        "skills this page needs, and prints the best ones for each flagged skill:",
        '10-practice-framework.md, "Many-to-many selection".',
        "",
        "A report gives practice only for the skills it flags. Per skill, Free shows",
        f"{pc.TIERS['free']['exercises_max']} exercise and {pc.TIERS['free']['tips_max']} tip, Pro up to "
        f"{pc.TIERS['pro']['exercises_max']} and {pc.TIERS['pro']['tips_max']}, moving on at each re-check.",
        "How many tries a day follows the stage of the row's own skill:",
        "",
        "| Stage | Score | Tries |",
        "|---|---|---|",
    ]
    bands = [
        ("focus", "below 4.5"),
        ("dev", "4.5 to 6.9"),
        ("good", "7 to 8.4"),
        ("strong", "8.5 and up"),
    ]
    for band, score in bands:
        d = pc.DOSAGE[band]
        tries = (
            f"{d['tries']} a day for {d['days']} days"
            if d["per"] == "day"
            else f"{d['tries']} once a week"
        )
        out.append(f"| {STAGE[band]} | {score} | {tries}, then check again |")
    out += ["", "## Contents", ""]
    for n in sorted(pc.FACTORS):
        name, fid = names[n]
        out.append(f"- [{n}. {name}](#{n}-{fid.replace('_', '-')})")
    for n in sorted(pc.FACTORS):
        name, fid = names[n]
        area = pc.FACTORS[n]
        note = ""
        if n in pc.PEN_FACTORS:
            note = " Scored by the pen only: never offered on a photo report."
        out += [
            "",
            f'<a id="{n}-{fid.replace("_", "-")}"></a>',
            f"## {n}. {name}",
            "",
            f"Factor id `{fid}`.{note}",
            "",
            "Under the skill on page 2:",
            "",
            "| | English | తెలుగు (draft) |",
            "|---|---|---|",
            f"| Why it helps | {cell(area['why'])} | {cell(area['i18n']['te']['why'])} |",
            f"| You'll know it's working when | {cell(area['win'])} | {cell(area['i18n']['te']['win'])} |",
            f"| More | vahinitech.com/{area['page']}.html | |",
            "",
            "| Level | Exercise | 1 try = | Steps | Example | Self-check | Worksheet | Script | Drawing | Helps |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for e in area["exercises"]:
            out.append(
                f"| {e['level']} | **{cell(e['title'])}** `{e['id']}` | 1 {e['unit']} | {cell(e['steps'])} | "
                f"{cell(e.get('example')) or '-'} | {cell(e.get('check'))} | {e.get('worksheet') or '-'} | {e['script']} | {e.get('model') or '-'} | {helps(e, names)} |"
            )
            out.append(telugu_exercise(e))
        out += ["", "| Tip | Text | Helps |", "|---|---|---|"]
        for t in area["tips"]:
            out.append(
                f"| `{t['id']}` | {cell(t['text'])} | {helps(t, names)} |"
            )
            out.append(telugu_tip(t))
    sp = pc.SPELLING
    out += [
        "",
        "## Spelling (a row only when the spelling check found a word)",
        "",
        "| Exercise | Steps |",
        "|---|---|",
    ]
    for e in sp["exercises"]:
        out.append(
            f"| **{cell(e['title'])}** `{e['id']}` | {cell(e['steps'])} |"
        )
        te = e["i18n"]["te"]
        out.append(
            f"| {TE_MARK} **{cell(te['title'])}** | {cell(te['steps'])} ({cell(te['check'])}) |"
        )
    out += ["", "| Tip | Text | Helps |", "|---|---|---|"]
    for t in sp["tips"]:
        out.append(f"| `{t['id']}` | {cell(t['text'])} | - |")
        out.append(telugu_tip(t))
    return "\n".join(out) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(
                "practice_map: docs/11-practice-map.md is out of date; run python scripts/practice_map.py"
            )
        print("practice_map: docs/11-practice-map.md is current")
        return
    OUT.write_text(text)
    print(f"practice_map: wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
